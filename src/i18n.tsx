type Variables = Record<string, string | number>
type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: TranslationKey, variables?: Variables) => string
}

const dictionaries: Record<Locale, Record<TranslationKey, string>> = { 'zh-CN': zhCN, en }
const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>('zh-CN')
  const t = useCallback(
    (key: TranslationKey, variables?: Variables) => {
      const template = dictionaries[locale][key]
      if (!variables) return template
      return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
    },
    [locale],
  )
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
